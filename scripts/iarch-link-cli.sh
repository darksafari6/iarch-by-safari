# Put the iarch-* CLI launchers on PATH under the names the session configuration uses.
#
# Usage: scripts/iarch-link-cli.sh [--dest DIR] [--force]
#        scripts/iarch-link-cli.sh --check [--dest DIR]
#        scripts/iarch-link-cli.sh --remove [--dest DIR] [--force]
#
# Why this exists
# ---------------
# The recovery bind in .config/hypr/keybind.lua runs `iarch-keybinds reset --all --yes`,
# and data/keybinds.default.json records that same command in the recovery entry. A bind
# that calls a command nobody installed is not a safety net, it is a rumour: on a session
# today the bind takes its own fallback and says on stderr that the CLI is missing. The
# repository has no console_scripts entry for it either -- the CLI is one file that finds
# its own package -- so the name has to come from somewhere, and this is where it comes
# from.
#
# What it writes
# --------------
# One small generated wrapper per command in $HOME/.local/bin (no sudo, no system
# directory), which execs the launcher in this checkout by absolute path. It is a
# generated file rather than a symlink for one reason: a symlink to scripts/ survives
# nothing that moves the checkout, and a wrapper can tell a person exactly which checkout
# it was linked from and what to re-run. Every wrapper carries a marker line so this
# script can tell its own files from anything else that happens to have the same name --
# it will not overwrite a file it did not write unless --force says to, and --force backs
# the other file up first.
#
# Running it twice changes nothing: an existing wrapper that already points at this
# checkout is left alone rather than rewritten.
#
# This is the minimum that makes the name resolve. The installer task in Part 6 owns the
# full version -- every iarch-* command, the desktop entry, the session PATH, and an
# uninstall driven by a state file -- and COMMANDS below is the list it extends.
set -euo pipefail

here="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
root="$(dirname -- "$here")"

#: The line every generated wrapper carries, and the only thing that identifies a file
#: here as ours. Changing it orphans every wrapper this script has written, so it is a
#: constant rather than something assembled per run.
MARKER='# Generated by scripts/iarch-link-cli.sh'

#: "name:launcher", relative to the repository root. Both entries are here for the same
#: reason: a bind in .config/hypr calls each of them by that exact name, so a session
#: without them has a recovery combo and a shortcut overlay that do nothing. The
#: installer task in Part 6 extends this list to the rest of the iarch-* commands.
COMMANDS=(
    "iarch-keybinds:scripts/iarch-keybinds.sh"
    "iarch-cheatsheet:scripts/iarch-cheatsheet.sh"
)

usage() {
    cat <<'USAGE'
Usage: scripts/iarch-link-cli.sh [--dest DIR] [--force]
       scripts/iarch-link-cli.sh --check [--dest DIR]
       scripts/iarch-link-cli.sh --remove [--dest DIR] [--force]

Links the iarch-* CLI launchers into DIR (default $HOME/.local/bin) under the names the
session configuration calls them by.

  --check    report whether every command is linked to this checkout, and change nothing
             (exit 1 if any is missing, foreign, or points somewhere else)
  --remove   delete the wrappers this script wrote, and only those
  --dest     the directory to link into; it is created if absent
  --force    overwrite a file this script did not write, after backing it up
  -h         this text

Writes as your normal user. It refuses to run as root, because a root-owned wrapper in a
user's ~/.local/bin is a broken install that looks like a working one.
USAGE
}

mode="link"
dest=""
force=0

while [ "$#" -gt 0 ]; do
    case "$1" in
        --check)  mode="check"; shift ;;
        --remove) mode="remove"; shift ;;
        --force)  force=1; shift ;;
        --dest)
            [ "$#" -ge 2 ] || { printf 'Error: --dest needs a directory.\n' >&2; exit 2; }
            dest="$2"; shift 2 ;;
        --dest=*) dest="${1#--dest=}"; shift ;;
        -h|--help) usage; exit 0 ;;
        *)
            printf 'Error: unknown option: %s\n' "$1" >&2
            usage >&2
            exit 2 ;;
    esac
done

if [ -z "$dest" ]; then
    dest="${HOME:-}/.local/bin"
fi
if [ -z "${HOME:-}" ] && [ "$mode" != "check" ]; then
    printf 'Error: HOME is not set, so there is no user directory to link into.\n' >&2
    printf 'Pass --dest DIR to say where the wrappers should go.\n' >&2
    exit 1
fi

if [ "$(id -u)" -eq 0 ] && [ "$mode" != "check" ]; then
    printf 'Error: refusing to run as root.\n' >&2
    printf 'These wrappers belong in a normal user'"'"'s ~/.local/bin. Run this as the\n' >&2
    printf 'user who owns the session; the installer calls sudo per command, never whole.\n' >&2
    exit 1
fi

#: Is this file one of ours, and does it point at the launcher we would write?
is_ours() {
    grep -qF "$MARKER" "$1" 2>/dev/null
}

points_at() {
    grep -qF "launcher='$2'" "$1" 2>/dev/null
}

#: Write a wrapper atomically: a temporary file in the destination directory, made
#: executable, then renamed. A half-written wrapper on PATH is worse than no wrapper,
#: because `command -v iarch-keybinds` succeeds and the exec then fails.
write_wrapper() {
    name="$1"
    launcher="$2"
    directory="$3"
    temporary="$directory/.$name.iarch-new.$$"

    cat > "$temporary" <<WRAPPER
#!/usr/bin/env bash
$MARKER -- do not edit this file.
#
# It points at the checkout it was linked from. If that checkout moves or is deleted this
# wrapper stops working on purpose and says so, rather than quietly running some other
# copy of the CLI. Re-run scripts/iarch-link-cli.sh from the new location to fix it.
launcher='$launcher'

if [ ! -x "\$launcher" ]; then
    printf 'Error: %s is gone or is not executable, so $name cannot run.\\n' "\$launcher" >&2
    printf 'Re-run scripts/iarch-link-cli.sh from the iArch checkout to relink it.\\n' >&2
    exit 70
fi

exec "\$launcher" "\$@"
WRAPPER
    chmod 755 "$temporary"
    mv -f "$temporary" "$directory/$name"
}

problems=0

link_one() {
    name="${1%%:*}"
    relative="${1#*:}"
    launcher="$root/$relative"
    target="$dest/$name"

    if [ ! -f "$launcher" ]; then
        printf '[FAIL] %s: %s is missing from this checkout\n' "$name" "$relative" >&2
        problems=$((problems + 1))
        return
    fi
    if [ ! -x "$launcher" ]; then
        printf '[FAIL] %s: %s is not executable, so a wrapper for it would fail\n' \
            "$name" "$relative" >&2
        problems=$((problems + 1))
        return
    fi

    if [ -e "$target" ] || [ -L "$target" ]; then
        if is_ours "$target"; then
            if points_at "$target" "$launcher"; then
                printf '[ OK ] %s: already linked to %s\n' "$name" "$launcher"
                return
            fi
            printf '[ .. ] %s: relinking from another checkout\n' "$name"
        elif [ "$force" -eq 1 ]; then
            kept="$target.iarch-backup"
            mv -f "$target" "$kept"
            printf '[ .. ] %s: %s was not ours; backed up to %s\n' "$name" "$target" "$kept"
        else
            printf '[FAIL] %s: %s exists and was not written by this script\n' \
                "$name" "$target" >&2
            printf '       It is left exactly as it is. Read it, then pass --force to\n' >&2
            printf '       replace it (which backs it up beside it first).\n' >&2
            problems=$((problems + 1))
            return
        fi
    fi

    write_wrapper "$name" "$launcher" "$dest"
    printf '[ OK ] %s: %s -> %s\n' "$name" "$target" "$launcher"
}

check_one() {
    name="${1%%:*}"
    relative="${1#*:}"
    launcher="$root/$relative"
    target="$dest/$name"

    if [ ! -e "$target" ]; then
        printf '[FAIL] %s: not linked (expected %s)\n' "$name" "$target" >&2
        problems=$((problems + 1))
        return
    fi
    if [ ! -x "$target" ]; then
        printf '[FAIL] %s: %s is not executable\n' "$name" "$target" >&2
        problems=$((problems + 1))
        return
    fi
    if ! is_ours "$target"; then
        printf '[FAIL] %s: %s was not written by this script\n' "$name" "$target" >&2
        problems=$((problems + 1))
        return
    fi
    if ! points_at "$target" "$launcher"; then
        printf '[FAIL] %s: linked, but to a different checkout than %s\n' \
            "$name" "$root" >&2
        problems=$((problems + 1))
        return
    fi
    printf '[ OK ] %s: %s -> %s\n' "$name" "$target" "$launcher"
}

remove_one() {
    name="${1%%:*}"
    target="$dest/$name"

    if [ ! -e "$target" ] && [ ! -L "$target" ]; then
        printf '[ OK ] %s: nothing to remove\n' "$name"
        return
    fi
    if ! is_ours "$target"; then
        if [ "$force" -ne 1 ]; then
            printf '[FAIL] %s: %s was not written by this script, so it is left alone\n' \
                "$name" "$target" >&2
            printf '       Pass --force to remove it anyway.\n' >&2
            problems=$((problems + 1))
            return
        fi
        printf '[ .. ] %s: removing a file this script did not write, because --force said to\n' \
            "$name"
    fi
    rm -f "$target"
    printf '[ OK ] %s: removed %s\n' "$name" "$target"
}

if [ "$mode" != "check" ] && [ ! -d "$dest" ]; then
    mkdir -p "$dest"
    printf 'Created %s\n' "$dest"
fi

for entry in "${COMMANDS[@]}"; do
    case "$mode" in
        link)   link_one "$entry" ;;
        check)  check_one "$entry" ;;
        remove) remove_one "$entry" ;;
    esac
done

if [ "$mode" = "link" ] && [ "$problems" -eq 0 ]; then
    case ":$PATH:" in
        *":$dest:"*) ;;
        *)
            printf '\nNote: %s is not on PATH, so the name will not resolve yet.\n' "$dest"
            printf 'Add this to your shell profile and to the session environment:\n'
            printf '    export PATH="%s:$PATH"\n' "$dest"
            ;;
    esac
fi

if [ "$problems" -ne 0 ]; then
    case "$mode" in
        check)  failed="verified" ;;
        link)   failed="linked" ;;
        remove) failed="removed" ;;
        *)      failed="handled" ;;
    esac
    printf '\n%d command(s) could not be %s.\n' "$problems" "$failed" >&2
    exit 1
fi

case "$mode" in
    link)   printf '\nLinked %d command(s) into %s.\n' "${#COMMANDS[@]}" "$dest" ;;
    check)  printf '\nAll %d command(s) are linked to this checkout.\n' \
                "${#COMMANDS[@]}" ;;
    remove) printf '\nRemoved the wrappers this script wrote from %s.\n' "$dest" ;;
esac
