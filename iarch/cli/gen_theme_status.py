"""Generate the theme status table from the catalogue of record."""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOGUE = ROOT / 'data/design/themes.json'
OUTPUT = ROOT / 'docs/themes/STATUS.md'


def render():
    data = json.loads(CATALOGUE.read_text(encoding='utf-8'))
    lines = ['# Theme status', '', '<!-- Generated by iarch/cli/gen_theme_status.py; do not edit. -->', '',
             'The reference pack is not offered for application. Planned themes are not finished.', '',
             '| Theme | Group | Status | Reference |', '| --- | --- | --- | --- |']
    for theme in data['themes']:
        lines.append(f"| {theme['name']} (`{theme['id']}`) | {theme['group']} | {theme['status']} | {theme['source_screenshot'] or '—'} |")
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != expected:
            print('theme status is out of date', file=sys.stderr)
            return 1
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
