-- The static half of the keyboard map.
--
-- Every bind this session ships is generated from data/keybinds.default.json into
-- .config/hypr/generated/keybinds.lua by iarch-keybinds, and that file is required
-- before this one (see .config/hypr/hyprland.lua). This file is the residue: the
-- place a bind goes only when the record genuinely cannot express it -- a submap,
-- a catchall, a device-scoped bind, or anything else that needs Lua the generator
-- does not model. Today there is nothing like that, so this file binds nothing.
--
-- Keeping it rather than deleting it is deliberate. hyprland.lua requires it, so a
-- bind that has to be hand-written has a home that is not the generated file, and
-- the next render cannot overwrite it. The ordering matters too, and only for a
-- total failure: generated.keybinds is required first, so a render that does not
-- parse at all registers nothing, this file registers nothing, and the registry is
-- empty -- which is exactly the condition under which the compositor trips its own
-- emergency binds (data/design/keybinds.json -> recovery). A render that parses and
-- then errors on one bind is the worse case and no ordering fixes it: the binds
-- before the error are live and the ones after are not, which is why iarch-keybinds
-- validates the whole map before it writes any of it.
--
-- Do not add a bind here that the record could hold. A bind in two places is two
-- handlers on one key, and which one runs depends on registration order.

